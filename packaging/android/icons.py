#!/usr/bin/env python3
"""Write the Android launcher icon from assets/app-icon/rabicraft.svg.

Android's AAPT2 compiles VectorDrawable XML the way it compiles PNGs, so the APK can carry the
repository's own master artwork instead of a raster nobody can regenerate offline. This translates
the SVG's presentation attributes into the VectorDrawable subset: a viewport, `pathData` per
`<path>`, and fills. Gradients, strokes and filters are refused rather than silently dropped.

    packaging/android/icons.py            # write the drawables
    packaging/android/icons.py --check    # fail if they are out of date (cargo xtask ci)

The SVG is the source; `packaging/icons.sh` renders the PNGs the other platforms install.
"""

import argparse
import re
import sys
from pathlib import Path
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parents[2]
SVG = ROOT / "assets/app-icon/rabicraft.svg"
RES = ROOT / "packaging/android/app/src/main/res"
SVG_NS = "{http://www.w3.org/2000/svg}"

# The adaptive icon: a 108 dp canvas, the 72 dp icon centred in it. The launcher crops the outer
# 18 dp on each side for its mask, so the artwork stays whole whatever shape the mask has.
VIEWPORT = 108
INSET = 18
SCALE = 72 / 512

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packaging/android/icons.py from assets/app-icon/rabicraft.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{density}dp"
    android:height="{density}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">"""


def die(message):
    sys.exit(f"icons.py: {message}")


def transform(view_box, width, height, inset, scale):
    """Map an SVG user-space point into the VectorDrawable's viewport."""
    min_x, min_y, box_w, box_h = view_box
    if abs(box_w / box_h - width / height) > 1e-6:
        die(f"the SVG viewBox {view_box} is not the {width}x{height} aspect the icon needs")
    return (lambda x, y: (inset + (x - min_x) * scale, inset + (y - min_y) * scale))


def path_data(d, point):
    """The SVG path in VectorDrawable syntax: same commands, points moved into the viewport."""
    tokens = re.findall(r"[MmLlHhVvCcSsQqTtAaZz]|-?\d*\.?\d+(?:[eE][-+]?\d+)?", d)
    out, i, command = [], 0, None
    arity = {"m": 2, "l": 2, "h": 1, "v": 1, "c": 6, "s": 4, "q": 4, "t": 2, "a": 7, "z": 0}

    def number(token):
        return float(token)

    def fmt(value):
        return f"{value:.3f}".rstrip("0").rstrip(".")

    while i < len(tokens):
        token = tokens[i]
        if token.isalpha():
            command = token
            i += 1
            if command.lower() == "z":
                out.append("Z")
            continue
        if command is None:
            die("the path starts with a number")
        kind = command.lower()
        count = arity[kind]
        if count == 0:
            die(f"unexpected arguments after {command}")
        args = [number(t) for t in tokens[i:i + count]]
        if len(args) != count:
            die(f"truncated arguments for {command} in {d[:40]}")
        i += count
        # VectorDrawable keeps relative and absolute commands; only the points move.
        if kind in ("m", "l", "t"):
            x, y = point(args[0], args[1])
            if command.isupper():
                out.append(f"{command}{fmt(x)},{fmt(y)}")
            else:
                out.append(f"{command}{fmt(args[0] * SCALE)},{fmt(args[1] * SCALE)}")
        elif kind in ("c", "s", "q"):
            pairs = list(zip(args[0::2], args[1::2]))
            moved = [point(x, y) if command.isupper() else (x * SCALE, y * SCALE) for x, y in pairs]
            out.append(command + " ".join(f"{fmt(x)},{fmt(y)}" for x, y in moved))
        elif kind in ("h", "v"):
            if command.isupper():
                absolute = point(args[0], 0)[0] - INSET if kind == "h" else point(0, args[0])[1] - INSET
                out.append(f"{command}{fmt(absolute)}")
            else:
                out.append(f"{command}{fmt(args[0] * SCALE)}")
        elif kind in ("a",):
            if command.isupper():
                die("absolute arcs are not translated; use the relative form")
            out.append("a" + ",".join(fmt(v) for v in args[:6]) + f",{fmt(args[6])}")
        else:
            die(f"unsupported command {command}")
    return "".join(out)


def colour(value):
    value = (value or "").strip()
    if re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        return f"#{value[1:].upper()}"
    if re.fullmatch(r"#[0-9a-fA-F]{3}", value):
        return "#" + "".join(c * 2 for c in value[1:]).upper()
    if value.startswith("url(") or value.startswith("rgb("):
        die(f"only solid #rrggbb fills are supported, not {value}")
    # Named colours: refuse rather than guess the palette.
    die(f"unsupported fill {value!r}")


def drawable(density, viewport, inset, source):
    """The icon as VectorDrawable XML at `density` (dp of the 108 dp canvas)."""
    root = ElementTree.fromstring(SVG.read_text(encoding="utf-8"))
    if root.tag != f"{SVG_NS}svg":
        die("the master is not an <svg>")
    box = root.get("viewBox")
    if not box:
        die("the master has no viewBox")
    view = tuple(float(v) for v in box.replace(",", " ").split())
    point = transform(view, view[2], view[3], inset, SCALE)
    if view[2] != 512 or view[3] != 512:
        die(f"the master's viewBox is {view}, expected 0 0 512 512")

    body = []
    group = root.find(f"{SVG_NS}g")
    # The master clips the tile's rounded corners. An adaptive icon's mask does that job: drawing
    # the clip as well would round the corners twice and show the background at each corner.
    for shapes in ([group] if group is not None else [root]):
        for child in shapes:
            if child.tag == f"{SVG_NS}path":
                d = path_data(child.get("d", ""), point)
                fill = colour(child.get("fill") or "#000000")
                body.append(f'    <path\n        android:fillColor="{fill}"\n        android:fillType="evenOdd"\n        android:pathData="{d}" />')
            elif child.tag == f"{SVG_NS}rect":
                # Only the full-bleed background is allowed: a rounded rect is the mask's job.
                if child.get("rx") not in (None, "0"):
                    continue
                x, y = point(float(child.get("x", 0)), float(child.get("y", 0)))
                w = float(child.get("width")) * SCALE
                h = float(child.get("height")) * SCALE
                fill = colour(child.get("fill") or "#000000")
                body.append(
                    f'    <path\n        android:fillColor="{fill}"\n        android:pathData="M{x:.3f},{y:.3f}h{w:.3f}v{h:.3f}h{-w:.3f}Z" />'
                )
            elif child.tag in (f"{SVG_NS}defs",):
                continue
            else:
                die(f"unsupported element {child.tag} in the master")
    if not body:
        die("the master has no drawable shapes")
    # An adaptive icon draws its background and foreground as separate layers, and the launcher
    # adds depth (parallax) between them. A full-bleed rectangle in the foreground would cover the
    # background layer and cancel that, so the tile goes to the background shader instead.
    full_bleed = [i for i, line in enumerate(body) if _is_full_bleed(line)]
    for i in reversed(full_bleed):
        del body[i]
    return HEADER.format(density=density, viewport=viewport) + "\n" + "\n".join(body) + "\n</vector>\n"


def _is_full_bleed(path: str) -> bool:
    """Whether a generated `<path>` covers the whole canvas: the master's background rectangle."""
    match = re.search(r'android:pathData="M([-\d.]+),([-\d.]+)h([\d.]+)v([\d.]+)h', path)
    return match is not None and abs(float(match.group(3)) - 512 * SCALE) < 0.01


def background() -> str:
    """The launcher's background layer: the master's own background colour, full bleed."""
    root = ElementTree.fromstring(SVG.read_text(encoding="utf-8"))
    group = root.find(f"{SVG_NS}g")
    for child in (group if group is not None else root):
        if child.tag == f"{SVG_NS}rect" and (child.get("rx") in (None, "0")):
            return colour(child.get("fill") or "#000000")
    die("the master has no full-bleed background rectangle")


TARGETS = {
    # (file, dp size of the drawable, viewport)
    "drawable/ic_launcher_foreground.xml": (108, 108),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail instead of writing")
    args = parser.parse_args()
    written = []
    for name, (density, viewport) in TARGETS.items():
        target = RES / name
        text = drawable(density, viewport, INSET, SVG)
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                die(f"{target.relative_to(ROOT)} is out of date: run packaging/android/icons.py")
            # The background went to the adaptive icon's own layer, from this master: a colour
            # that drifted from it would show as a seam at the launcher's mask.
            colors = RES / "values/colors.xml"
            if not colors.is_file() or f">{background()}<" not in colors.read_text(encoding="utf-8"):
                die("res/values/colors.xml no longer holds the master's background colour: run packaging/android/icons.py")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        written.append(target)
    if args.check:
        print("android icons: up to date")
    else:
        for path in written:
            print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
